def _lower_camel(name: str) -> str:
    return name[0].lower() + name[1:]


def _render_enum(enum_type: type[StrEnum]) -> str:
    constant_name = f"{_lower_camel(enum_type.__name__)}Values"
    values = json.dumps([member.value for member in enum_type], indent=2)
    return (
        f"export const {constant_name} = {values} as const;\n"
        f"export type {enum_type.__name__} = (typeof {constant_name})[number];\n"
    )


def render_typescript_contract() -> str:
    sections = [
        "// Generated by `eea openapi typescript`; do not edit manually.\n",
        "export interface ApiEnvelope<T> {\n"
        "  success: true;\n"
        "  data: T;\n"
        "  request_id: string;\n"
        "}\n",
    ]
    sections.extend(_render_enum(enum_type) for enum_type in CORE_ENUMS)
    sections.extend(
        [
            "export interface ApiError {\n"
            "  code: EngineeringErrorCode;\n"
            "  message: string;\n"
            "  details: Record<string, unknown>;\n"
            "}\n",
            "export interface ProjectData {\n"
            "  id: string;\n"
            "  schema_version: string;\n"
            "  revision: number;\n"
            "  created_at: string;\n"
            "  updated_at: string;\n"
            "  metadata: Record<string, unknown>;\n"
            "  name: string;\n"
            "  description: string;\n"
            "  status: ProjectStatus;\n"
            "}\n",
            "export interface DocumentUploadRequest {\n"
            "  filename: string;\n"
            "  content_base64: string;\n"
            "  document_type: DocumentType;\n"
            "  vendor: string | null;\n"
            "  product: string | null;\n"
            "  version_label: string | null;\n"
            "}\n",
            "export interface DocumentData {\n"
            "  id: string;\n"
            "  schema_version: string;\n"
            "  revision: number;\n"
            "  created_at: string;\n"
            "  updated_at: string;\n"
            "  metadata: Record<string, unknown>;\n"
            "  project_id: string | null;\n"
            "  filename: string;\n"
            "  document_type: DocumentType;\n"
            "  vendor: string | null;\n"
            "  product: string | null;\n"
            "  version_label: string | null;\n"
            "  content_hash: string;\n"
            "  storage_uri: string;\n"
            "  parse_status: DocumentParseStatus;\n"
            "  parse_error: string | null;\n"
            "}\n",
            "export interface EvidenceCreateRequest {\n"
            "  evidence_type: EvidenceType;\n"
            "  locator: Record<string, unknown>;\n"
            "  source_uri: string | null;\n"
            "  content_hash: string | null;\n"
            "  summary: string;\n"
            "}\n",
            "export interface EvidenceData {\n"
            "  id: string;\n"
            "  schema_version: string;\n"
            "  revision: number;\n"
            "  created_at: string;\n"
            "  updated_at: string;\n"
            "  metadata: Record<string, unknown>;\n"
            "  project_id: string | null;\n"
            "  evidence_type: EvidenceType;\n"
            "  locator: Record<string, unknown>;\n"
            "  source_uri: string | null;\n"
            "  content_hash: string | null;\n"
            "  files: string[];\n"
            "  summary: string;\n"
            "}\n",
        ]
    )
    return "\n".join(sections)
